package game

type Point struct {
	X, Y int
}

type Shape [4]Point

type Form int

const (
	I Form = iota
	O
	T
	S
	Z
	J
	L
	FormCount
)

type Rotation uint8

const (
	Rot0 Rotation = iota
	Rot90
	Rot180
	Rot270
	rotCount
)

func (r Rotation) Next() Rotation {
	return (r + 1) % rotCount
}

func (r Rotation) Prev() Rotation {
	return (r + rotCount - 1) % rotCount
}

